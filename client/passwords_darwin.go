package main

import (
	"context"
	"encoding/base64"
	"encoding/json"
	"errors"
	"os/exec"
	"strings"
	"time"
)

const passwordService = "com.sshvnc.desktop.credentials"

type keychainPasswordStore struct{}

func newPasswordStore() passwordStore { return keychainPasswordStore{} }

func keychainCommand(args ...string) ([]byte, error) {
	ctx, cancel := context.WithTimeout(context.Background(), 30*time.Second)
	defer cancel()
	return exec.CommandContext(ctx, "/usr/bin/security", args...).Output()
}

func (keychainPasswordStore) Get(ref string) (savedPasswords, error) {
	data, err := keychainCommand("find-generic-password", "-s", passwordService, "-a", ref, "-w")
	if err != nil {
		var exit *exec.ExitError
		if errors.As(err, &exit) && exit.ExitCode() == 44 {
			return savedPasswords{}, errPasswordNotFound
		}
		return savedPasswords{}, errors.New("无法读取钥匙串中的密码，请确认登录钥匙串已解锁")
	}
	decoded, err := base64.StdEncoding.DecodeString(strings.TrimSpace(string(data)))
	var passwords savedPasswords
	if err == nil {
		err = json.Unmarshal(decoded, &passwords)
	}
	if err != nil {
		return savedPasswords{}, errors.New("钥匙串中的密码记录无效")
	}
	return passwords, nil
}

func (keychainPasswordStore) Set(ref string, passwords savedPasswords) error {
	data, err := json.Marshal(passwords)
	if err != nil {
		return err
	}
	// Pass the encoded secret on stdin, never in process arguments or a shell.
	// The account is generated by crypto/rand and contains no CLI delimiters.
	if strings.ContainsAny(ref, " \t\r\n\"'\\") {
		return errors.New("无效的密码记录标识")
	}
	ctx, cancel := context.WithTimeout(context.Background(), 30*time.Second)
	defer cancel()
	cmd := exec.CommandContext(ctx, "/usr/bin/security", "-i")
	cmd.Stdin = strings.NewReader("add-generic-password -U -s " + passwordService + " -a " + ref + " -w " + base64.StdEncoding.EncodeToString(data) + "\n")
	if err := cmd.Run(); err != nil {
		return errors.New("保存密码到钥匙串失败，请确认登录钥匙串已解锁")
	}
	return nil
}

func (keychainPasswordStore) Delete(ref string) error {
	_, err := keychainCommand("delete-generic-password", "-s", passwordService, "-a", ref)
	if err != nil {
		var exit *exec.ExitError
		if errors.As(err, &exit) && exit.ExitCode() == 44 {
			return nil
		}
		return errors.New("删除钥匙串中的密码失败")
	}
	return nil
}
