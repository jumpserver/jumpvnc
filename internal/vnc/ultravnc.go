package vnc

import (
	"bufio"
	"encoding/hex"
	"errors"
	"fmt"
	"net"
	"os"
	"path/filepath"
	"strings"

	"sshvnc/internal/config"
)

func checkUltraVNC(cfg config.VNC, dir string) error {
	marker, err := os.Stat(filepath.Join(dir, "ultravnc.portable"))
	if err != nil || !marker.Mode().IsRegular() {
		return errors.New("UltraVNC needs an ultravnc.portable marker beside the executable")
	}
	f, err := os.Open(filepath.Join(dir, "ultravnc.ini"))
	if err != nil {
		return fmt.Errorf("open ultravnc.ini: %w", err)
	}
	defer f.Close()

	_, port, _ := net.SplitHostPort(cfg.Listen)
	inputs := "1"
	if cfg.ViewOnly {
		inputs = "0"
	}
	required := []struct{ key, value string }{
		{"socketconnect", "1"},
		{"allowloopback", "1"},
		{"loopbackonly", "1"},
		{"useipv6", "0"},
		{"httpconnect", "0"},
		{"authrequired", "1"},
		{"mslogonrequired", "0"},
		{"filetransferenabled", "0"},
		{"autoportselect", "0"},
		{"portnumber", port},
		{"inputsenabled", inputs},
	}

	values := make(map[string]string)
	section := ""
	scanner := bufio.NewScanner(f)
	for scanner.Scan() {
		line := strings.TrimSpace(scanner.Text())
		line = strings.TrimPrefix(line, "\uFEFF")
		if line == "" || strings.HasPrefix(line, ";") {
			continue
		}
		if strings.HasPrefix(line, "[") && strings.HasSuffix(line, "]") {
			section = strings.ToLower(strings.TrimSpace(line[1 : len(line)-1]))
			continue
		}
		key, value, ok := strings.Cut(line, "=")
		if !ok || section == "" {
			return errors.New("invalid ultravnc.ini entry")
		}
		key = section + "." + strings.ToLower(strings.TrimSpace(key))
		if _, seen := values[key]; seen {
			return errors.New("duplicate ultravnc.ini entry")
		}
		values[key] = strings.TrimSpace(value)
	}
	if err := scanner.Err(); err != nil {
		return err
	}
	for _, setting := range required {
		if values["admin."+setting.key] != setting.value {
			return fmt.Errorf("ultravnc.ini [admin] requires %s=%s", setting.key, setting.value)
		}
	}
	if !validPassword(values["ultravnc.passwd"]) {
		return errors.New("ultravnc.ini requires a valid [UltraVNC] passwd generated by UltraVNC")
	}
	return nil
}

func validPassword(value string) bool {
	data, err := hex.DecodeString(value)
	if err != nil || len(data) != 9 {
		return false
	}
	var checksum, nonzero byte
	for _, b := range data[:8] {
		checksum += b
		nonzero |= b
	}
	return nonzero != 0 && checksum == data[8]
}
